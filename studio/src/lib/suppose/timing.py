# Suppose Then: write <episode>/TIMING.txt (shot start, length, mid frame, spoken line) from vo.json + shotlist.ts.
# Uses JS rounding so it matches Full.tsx exactly. Usage (from studio/): python src/lib/suppose/timing.py src/episodes/<slug>
import json, math, sys
E = sys.argv[1].rstrip('/') + '/'
R = lambda x: math.floor(x + 0.5)
vo = json.load(open(E + 'vo.json', encoding='utf-8'))
src = open(E + 'shotlist.ts', encoding='utf-8').read()
rows = json.loads(src[src.index('= [') + 2:src.rindex(';')])
F = 30; cur = 0; sc = None; L = []
for l in vo:
    if l['scene'] != sc: sc = l['scene']; cur += R(0.35 * F)
    af = math.ceil(l['seconds'] * F); L.append((cur, af)); cur += af + R(l['pauseAfter'] * F)
tot = cur; end = tot + R(3.5 * F)
st = [0 if (r['line'] == 0 and r['frac'] == 0) else (tot - 15 if r['line'] < 0 else L[r['line']][0] + R(L[r['line']][1] * r['frac'])) for r in rows]
est = any(l.get('estimated') for l in vo)
out = [f"# shot timing (generated by lib/suppose/timing.py{'; ESTIMATED voice, will change' if est else ''}; 30 fps). id | act | start | length (s) | mid | spoken line", '']
for i, r in enumerate(rows):
    e = st[i + 1] if i + 1 < len(st) else end; d = e - st[i]
    out.append(f"{r['id']} | {r['act']} | {st[i]} | {d} ({d/30:.1f}s) | {st[i] + d // 2} | {vo[r['line']]['text'] if r['line'] >= 0 else '(end card)'}")
open(E + 'TIMING.txt', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
ds = [int(o.split(' | ')[3].split()[0]) for o in out[2:]]
print(f"{len(rows)} shots, total {end/30:.1f}s, min {min(ds)/30:.1f}s, max {max(ds)/30:.1f}s, avg {sum(ds)/len(ds)/30:.1f}s; long: {[o.split(' | ')[0] for o in out[2:] if int(o.split(' | ')[3].split()[0]) > 270]}")

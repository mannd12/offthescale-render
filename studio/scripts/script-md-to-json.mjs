// Converts episodes/<slug>/script.md (the human-edited draft) into episodes/<slug>/script.json
// (what TTS and the timeline consume). Scenes = "## " headings from "## Cold open" onward;
// lines = sentence groups (a paragraph split at sentence ends, joined up to ~220 chars) so the
// animation can key to beats. Stage directions *[...]* and blockquotes are dropped; a trailing
// "*[... caption ...]*" on a sentence is kept only as `cue` for the storyboard.
// Usage: node scripts/script-md-to-json.mjs <slug> [--voice en-US-Chirp3-HD-Aoede] [--speed 1.15]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const [slug, ...flags] = process.argv.slice(2);
if (!slug) {
  console.error("usage: node scripts/script-md-to-json.mjs <slug> [--voice v] [--speed s]");
  process.exit(1);
}
const opt = (name, def) => {
  const i = flags.indexOf(`--${name}`);
  return i > -1 ? flags[i + 1] : def;
};

const dir = path.join(ROOT, "..", "episodes", slug);
const md = fs.readFileSync(path.join(dir, "script.md"), "utf8");
const titleLine = md.split("\n").find((l) => l.startsWith("# ")) ?? "# Untitled";
const title = titleLine.replace(/^#\s*[A-Z]\d+\s*·\s*/, "").replace(/^#\s*/, "").trim();

const startIdx = md.indexOf("\n## Cold open");
if (startIdx < 0) throw new Error("script.md needs a '## Cold open' heading");
const body = md.slice(startIdx + 1);

const sceneId = (heading, n) => {
  const h = heading.toLowerCase();
  if (h.startsWith("cold open")) return "cold";
  if (h.startsWith("closer")) return "closer";
  const m = h.match(/^(\d+)\s*·/);
  return m ? `l${String(m[1]).padStart(2, "0")}` : `s${n}`;
};

const cleanSentence = (s) =>
  s
    .replace(/\*\[[^\]]*\]\*/g, "") // stage directions / captions
    .replace(/\*/g, "") // emphasis markers
    .replace(/\s+/g, " ")
    .trim();

const scenes = [];
let cur = null;
for (const raw of body.split("\n")) {
  if (raw.startsWith("## ")) {
    const heading = raw.slice(3).trim();
    cur = { id: sceneId(heading, scenes.length), name: heading.replace(/^\d+\s*·\s*/, "").replace(/\s*—.*$/, "").trim(), lines: [] };
    scenes.push(cur);
    continue;
  }
  if (!cur) continue;
  const line = raw.trim();
  if (/^-{3,}$/.test(line)) break; // a horizontal rule after the body = the footer (word count etc.); stop
  if (!line || line.startsWith(">") || /^\*\[.*\]\*$/.test(line)) continue; // blank, note, pure stage direction
  const cue = (line.match(/\*\[([^\]]*caption[^\]]*)\]\*/i) ?? [])[1];
  const text = cleanSentence(line);
  if (!text) continue;
  // split into sentence groups of up to ~220 characters
  // Split only where a terminator is followed by whitespace, and never after a single-letter
  // abbreviation ("U.S. Navy"). The old match-based regex silently DROPPED any sentence whose
  // period was followed by a non-space ("U.S.", "1.016"), losing narration (fixed 2026-09-25).
  const sentences = text.split(/(?<=[.!?…]["”)]?)(?<!\b[A-Z]\.)\s+/).map((s) => s.trim()).filter(Boolean);
  let buf = "";
  const groups = [];
  for (const s of sentences) {
    if (buf && (buf + " " + s).length > 220) {
      groups.push(buf);
      buf = s;
    } else buf = buf ? `${buf} ${s}` : s;
  }
  if (buf) groups.push(buf);
  groups.forEach((g, i) => {
    const entry = { text: g };
    if (i === groups.length - 1) entry.pause = 0.55; // paragraph end breathes
    if (cue && i === groups.length - 1) entry.cue = cue;
    cur.lines.push(entry);
  });
}

const out = {
  title,
  _source: `episodes/${slug}/script.md — generated by scripts/script-md-to-json.mjs; edit the .md, not this file. Add 'say' overrides here only via a patch file (episodes/${slug}/say.json).`,
  engine: "google",
  voice: opt("voice", "en-US-Chirp3-HD-Aoede"),
  speed: Number(opt("speed", "1.15")),
  scenes,
};

// pronunciation overrides survive regeneration: episodes/<slug>/say.json = { "<exact text>": "<spoken>" }
const sayPath = path.join(dir, "say.json");
if (fs.existsSync(sayPath)) {
  const say = JSON.parse(fs.readFileSync(sayPath, "utf8"));
  // keys match as substrings, so a sentence group that contains the phrase still gets the override
  for (const sc of scenes)
    for (const l of sc.lines) {
      let spoken = l.text;
      for (const [k, v] of Object.entries(say)) if (spoken.includes(k)) spoken = spoken.replace(k, v);
      if (spoken !== l.text) l.say = spoken;
    }
}

fs.writeFileSync(path.join(dir, "script.json"), JSON.stringify(out, null, 2) + "\n");
const n = scenes.reduce((a, s) => a + s.lines.length, 0);
const words = scenes.flatMap((s) => s.lines).reduce((a, l) => a + l.text.split(/\s+/).length, 0);
console.log(`${slug}: ${scenes.length} scenes, ${n} lines, ${words} words (~${(words / 190).toFixed(1)} min) -> episodes/${slug}/script.json`);
